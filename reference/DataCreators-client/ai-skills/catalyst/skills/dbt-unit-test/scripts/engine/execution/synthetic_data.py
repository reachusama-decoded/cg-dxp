"""
dbt-unit-test Synthetic Data Generator.

Prepares synthetic seed data (generated by the LLM) for consumption by
DBTTestRunner.  For in-memory execution engines (pyspark, pandas) no file
I/O is needed — the raw input_data dict is returned as-is.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


class SyntheticDataGenerator:
    """
    Prepares LLM-generated seed data for dbt-unit-test test execution.

    Parameters
    ----------
    seed_dir : Directory used by the test runner for context (not written to).
    """

    def __init__(self, seed_dir: str | Path):
        self.seed_dir = Path(seed_dir)

    # ------------------------------------------------------------------
    # Public
    # ------------------------------------------------------------------

    def write_seeds(
        self,
        test_id: str,
        model_name: str,
        input_data: dict[str, list[dict[str, Any]]],
    ) -> dict[str, list[dict[str, Any]]]:
        """
        Prepare seed data for a single test case.

        For in-memory execution (pyspark / pandas) the data is returned
        immediately without touching the filesystem.

        Parameters
        ----------
        test_id    : Unique identifier for the test case (e.g. "TC001").
        model_name : Name of the DBT model under test.
        input_data : Dict mapping source/ref table names to lists of row dicts.

        Returns
        -------
        The same ``input_data`` dict, ready for ``DBTTestRunner.load_seeds()``.
        """
        total_rows = sum(len(rows) for rows in input_data.values())
        logger.debug(
            "[dbt-unit-test] write_seeds: test_id=%s model=%s tables=%d total_rows=%d",
            test_id, model_name, len(input_data), total_rows,
        )
        return input_data
