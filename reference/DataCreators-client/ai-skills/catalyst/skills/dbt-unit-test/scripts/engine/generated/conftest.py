"""
Pytest conftest for dbt-unit-test generated test scripts.

Provides:
  - ``dbt_unit_test_config``   — dict of runtime configuration (project_root, dbt_target, db_connection_string)
  - ``dbt_unit_test_db_conn``  — optional DB connection (skips DB-dependent tests when absent)

Configuration is read in this priority order:
  1. Pytest CLI options  (--dbt-unit-test-target, --dbt-unit-test-db-conn)
  2. Environment variables (DBT_UNIT_TEST_DBT_TARGET, DBT_UNIT_TEST_DB_CONNECTION, DBT_UNIT_TEST_PROJECT_ROOT)
  3. Defaults (target=dev, no DB connection)
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

# ---------------------------------------------------------------------------
# Make the engine package importable from generated test scripts.
# engine/ lives two directories above this conftest:
#   scripts/engine/generated/conftest.py  →  scripts/
# ---------------------------------------------------------------------------
_SCRIPTS_DIR = Path(__file__).resolve().parent.parent.parent
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

# Project root: use cwd so this works both during development and when installed via pip.
# When installed, __file__ points inside site-packages, not the user's project.
# Run pytest from your DBT project root, or set DBT_UNIT_TEST_PROJECT_ROOT env var.
_PROJECT_ROOT = Path.cwd()


# ---------------------------------------------------------------------------
# CLI options
# ---------------------------------------------------------------------------

def pytest_addoption(parser: pytest.Parser) -> None:
    group = parser.getgroup("dbt-unit-test", "dbt-unit-test AI test runner options")
    group.addoption(
        "--dbt-unit-test-target",
        default = None,
        help    = "DBT target profile to use (overrides DBT_UNIT_TEST_DBT_TARGET env var)",
    )
    group.addoption(
        "--dbt-unit-test-db-conn",
        default = None,
        help    = "SQLAlchemy connection string (overrides DBT_UNIT_TEST_DB_CONNECTION env var)",
    )
    group.addoption(
        "--dbt-unit-test-project-root",
        default = None,
        help    = "Absolute path to DBT project root (overrides DBT_UNIT_TEST_PROJECT_ROOT env var)",
    )
    group.addoption(
        "--dbt-unit-test-executor",
        default = None,
        choices = ["pandas", "pyspark"],
        help    = "SQL execution engine for dbt-unit-test: 'pandas' (passthrough, default) or 'pyspark' (real SQL via local Spark)",
    )


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------

@pytest.fixture(scope="session")
def dbt_unit_test_config(request: pytest.FixtureRequest) -> dict:
    """
    Session-scoped configuration dict for the dbt-unit-test runner.

    Keys
    ----
    project_root           : Path to DBT project
    dbt_target             : DBT target name
    db_connection_string   : SQLAlchemy connection string (may be None)
    """
    target = (
        request.config.getoption("--dbt-unit-test-target")
        or os.environ.get("DBT_UNIT_TEST_DBT_TARGET", "dev")
    )
    db_conn = (
        request.config.getoption("--dbt-unit-test-db-conn")
        or os.environ.get("DBT_UNIT_TEST_DB_CONNECTION")
    )
    project_root = (
        request.config.getoption("--dbt-unit-test-project-root")
        or os.environ.get("DBT_UNIT_TEST_PROJECT_ROOT", str(_PROJECT_ROOT))
    )
    executor = (
        request.config.getoption("--dbt-unit-test-executor")
        or os.environ.get("DBT_UNIT_TEST_EXECUTOR", "pandas")
    )
    return {
        "project_root":         project_root,
        "dbt_target":           target,
        "db_connection_string": db_conn,
        "executor":             executor,
    }


@pytest.fixture(scope="session")
def dbt_unit_test_db_conn(dbt_unit_test_config: dict):
    """
    Returns the DB connection string, or skips the test if none is configured.
    Use this fixture only in tests that *require* a live DB.
    """
    conn = dbt_unit_test_config.get("db_connection_string")
    if not conn:
        pytest.skip(
            "No DB connection configured. "
            "Set DBT_UNIT_TEST_DB_CONNECTION env var or pass --dbt-unit-test-db-conn to pytest."
        )
    return conn


# ---------------------------------------------------------------------------
# Markers
# ---------------------------------------------------------------------------

def pytest_configure(config: pytest.Config) -> None:
    config.addinivalue_line(
        "markers",
        "dbt_unit_test_ai: mark a test as AI-generated by dbt-unit-test",
    )
    config.addinivalue_line(
        "markers",
        "dbt_unit_test_synthetic: mark a test that uses synthetic data",
    )
    config.addinivalue_line(
        "markers",
        "dbt_unit_test_requires_db: mark a test that requires a live DB connection",
    )
