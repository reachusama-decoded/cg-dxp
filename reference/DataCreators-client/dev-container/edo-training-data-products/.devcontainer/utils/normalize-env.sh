#!/bin/sh
# Normalize environment variables by removing surrounding quotes
# This allows users to optionally quote values in .env without breaking downstream tools
#
# This script creates a persistent profile script that ALL shells will source,
# ensuring normalized variables are available to all processes (DBT, Databricks CLI, etc.)
#
# Examples of acceptable .env formats:
#   DATABRICKS_HOST=https://...
#   DATABRICKS_HOST="https://..."
#   DATABRICKS_HOST='https://...'

set -e

# Function to remove surrounding quotes from a variable value
strip_quotes() {
    local value="$1"
    # Remove surrounding quotes (both single and double)
    echo "$value" | sed "s/^['\"]//;s/['\"]$//"
}

# Read current environment variables and strip quotes
DATABRICKS_HOST_CLEAN=$(strip_quotes "$DATABRICKS_HOST")
DATABRICKS_TOKEN_CLEAN=$(strip_quotes "$DATABRICKS_TOKEN")
DATABRICKS_HTTP_PATH_CLEAN=$(strip_quotes "$DATABRICKS_HTTP_PATH")
DBT_CATALOG_CLEAN=$(strip_quotes "${DBT_CATALOG:-}")
DBT_SCHEMA_CLEAN=$(strip_quotes "${DBT_SCHEMA:-}")

# Write normalized variables to a profile script that all shells will source
# This ensures DBT, Python, and all other processes get clean values
cat > /etc/profile.d/databricks-env.sh <<EOF
# Auto-generated by normalize-env.sh
# Normalized Databricks environment variables (quotes stripped)
export DATABRICKS_HOST="${DATABRICKS_HOST_CLEAN}"
export DATABRICKS_TOKEN="${DATABRICKS_TOKEN_CLEAN}"
export DATABRICKS_HTTP_PATH="${DATABRICKS_HTTP_PATH_CLEAN}"
export DBT_HTTP_PATH="${DATABRICKS_HTTP_PATH_CLEAN}"
if [ -n "${DBT_CATALOG_CLEAN}" ]; then
  export DBT_CATALOG="${DBT_CATALOG_CLEAN}"
fi
if [ -n "${DBT_SCHEMA_CLEAN}" ]; then
  export DBT_SCHEMA="${DBT_SCHEMA_CLEAN}"
fi
export DBT_HOST="${DATABRICKS_HOST_CLEAN}"
export DBT_ACCESS_TOKEN="${DATABRICKS_TOKEN_CLEAN}"
EOF

chmod 644 /etc/profile.d/databricks-env.sh

# Also source it immediately for the current shell
export DATABRICKS_HOST="${DATABRICKS_HOST_CLEAN}"
export DATABRICKS_TOKEN="${DATABRICKS_TOKEN_CLEAN}"
export DATABRICKS_HTTP_PATH="${DATABRICKS_HTTP_PATH_CLEAN}"
export DBT_HTTP_PATH="${DATABRICKS_HTTP_PATH_CLEAN}"
if [ -n "${DBT_CATALOG_CLEAN}" ]; then
    export DBT_CATALOG="${DBT_CATALOG_CLEAN}"
fi
if [ -n "${DBT_SCHEMA_CLEAN}" ]; then
    export DBT_SCHEMA="${DBT_SCHEMA_CLEAN}"
fi
export DBT_HOST="${DATABRICKS_HOST_CLEAN}"
export DBT_ACCESS_TOKEN="${DATABRICKS_TOKEN_CLEAN}"

echo "✓ Databricks environment variables normalized (quotes removed)"
